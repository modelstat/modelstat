export const PROCESSING_VERSION = 18;

export interface ProcessingState {
  processingVersion: number | null;
  setProcessingVersion(v: number): void;
  wipeCursors(): void;
}

/**
 * On startup: if the stored processing version is older than the
 * compiled-in one (or absent), wipe cursors and stamp the new
 * version. Returns a description of what happened so the caller can
 * surface it in startup logs.
 */
export function reconcileProcessingVersion(state: ProcessingState): {
  changed: boolean;
  from: number;
  to: number;
} {
  const stored = state.processingVersion ?? 1;
  if (stored >= PROCESSING_VERSION) {
    return { changed: false, from: stored, to: PROCESSING_VERSION };
  }
  state.wipeCursors();
  state.setProcessingVersion(PROCESSING_VERSION);
  return { changed: true, from: stored, to: PROCESSING_VERSION };
}
