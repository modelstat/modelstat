/**
 * Local processing-pipeline version — the marker that lets a new
 * daemon build force a re-scan of every previously-uploaded session.
 *
 * Why we need it: file cursors in `state.cursor` track "I've uploaded
 * up to byte N of this JSONL", so a normal restart only ships new
 * events. But when we change the pipeline itself (new summariser
 * model, different sampling, new redaction pass, new segment
 * boundary heuristics), every previously-uploaded segment is now
 * stale even though the underlying JSONL hasn't moved.
 *
 * The fix: bake a single integer into this file. On startup the
 * daemon compares it to the integer written into `state.cursor`'s
 * sibling field. If the compiled-in version is HIGHER than the
 * stored one, wipe every cursor so the next scan re-reads the world
 * from the start, runs every event through the current pipeline,
 * and ships fresh segments.
 *
 * **Bump this whenever the segment shape changes.** Example
 * triggers — DO bump:
 *   • Summariser model swap (e.g. Ollama → bundled Qwen3.5-4B in 0.0.27).
 *   • Summariser prompt change that materially shifts output.
 *   • Excerpt sampling strategy / size cap.
 *   • Segment boundary heuristic change.
 *   • PII redaction rules.
 *   • content_excerpt extraction in a parser (claude-code, codex, etc).
 *
 * Don't bump for:
 *   • Bugfixes that don't affect segment content.
 *   • Heartbeat / discovery / service-install changes.
 *   • Dashboard or backend-only changes.
 *
 * A re-scan REPLACES existing segments by segment_id in place — no
 * duplicates, no orphans. (Where the segment_id hash doesn't change
 * because the inputs didn't change, but the abstract does because the
 * summariser did.)
 */

